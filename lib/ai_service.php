{
    $system = "Ты — строгий и справедливый экзаменатор по моделированию бизнес-процессов в нотации BPMN 2.0 "
        . "для госслужащих Казахстана (методика реинжиниринга бизнес-процессов госорганов). "
        . "Тебе дают текст задания, эталон и схему участника в текстовом виде. "
        . "Схема участника может отличаться от эталона формулировками и разбиением на шаги — это допустимо, "
        . "если логика процесса, участники и ветвления переданы верно.\n\n"
        . "Критерии оценки:\n" . aiGradingRubric()
        . "\n\nОтвечай строго JSON-объектом:\n"
        . '{"score": <целое 0..' . $max . '>, "summary": "<2-3 предложения>", '
        . '"errors": ["<конкретная ошибка>", ...], "strengths": ["<что сделано верно>", ...]}';

    $user = "Задание (максимум {$max} баллов):\n" . $task['description']
        . "\n\n" . $reference
        . "\n\nСхема участника:\n" . $studentSummary;
    $found = array_merge($structure['issues'] ?? [], $structure['comparison'] ?? []);
    if ($found) {
        $user .= "\n\nСтруктурные замечания уже найдены алгоритмом (учти их в баллах, но не переписывай в errors):\n- "
            . implode("\n- ", $found)
            . "\nТвоя главная задача — смысл: соответствуют ли подписи, участники и порядок действий тексту задания.";
    }

    $json = aiChatJson([
        ['role' => 'system', 'content' => $system],
        ['role' => 'user', 'content' => $user],
    ], 'grader');

    $score = (int)round((float)($json['score'] ?? 0));

    return [
        'taskId' => $task['id'],
        'max' => $max,
        'score' => max(0, min($max, $score)),
        'summary' => (string)($json['summary'] ?? ''),
        'errors' => array_values(array_map('strval', (array)($json['errors'] ?? []))),
        'strengths' => array_values(array_map('strval', (array)($json['strengths'] ?? []))),
    ];
}

