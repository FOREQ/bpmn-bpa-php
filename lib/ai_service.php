/** Извлекает текст из загруженного файла: .txt, .md, .docx. */
function aiExtractSourceText(string $path, string $originalName): string
{
    $ext = strtolower(pathinfo($originalName, PATHINFO_EXTENSION));

    if ($ext === 'docx') {
        if (!class_exists(ZipArchive::class)) {
            throw new RuntimeException('Для .docx нужно PHP-расширение zip');
        }
        $zip = new ZipArchive();
        if ($zip->open($path) !== true) {
            throw new InvalidArgumentException('Не удалось открыть .docx');
        }
        $xml = (string)$zip->getFromName('word/document.xml');
        $zip->close();
        if ($xml === '') {
            throw new InvalidArgumentException('В .docx не найден текст');
        }
        $xml = preg_replace('#</w:p>#', "\n", $xml);
        $xml = preg_replace('#<w:tab/>#', "\t", $xml);
        $text = html_entity_decode(strip_tags($xml), ENT_QUOTES | ENT_XML1, 'UTF-8');
    } elseif (in_array($ext, ['txt', 'md'], true)) {
        $text = (string)file_get_contents($path);
        if (!mb_check_encoding($text, 'UTF-8')) {
            $text = mb_convert_encoding($text, 'UTF-8', 'Windows-1251');
        }
    } else {
        throw new InvalidArgumentException('Поддерживаются файлы .docx, .txt и .md');
    }

    $text = preg_replace("/[ \t]+/u", ' ', $text);
    $text = trim(preg_replace("/\n{3,}/", "\n\n", $text));

    return $text;
}

function aiSaveSource(PDO $pdo, string $title, string $content): int
{
    ensureAiSchema($pdo);
    $content = trim($content);
    if (mb_strlen($content) < 200) {
        throw new InvalidArgumentException('Текст методички слишком короткий');
    }
    if (strlen($content) > AI_SOURCE_MAX_CHARS) {
        throw new InvalidArgumentException('Текст методички слишком большой (максимум ~2 МБ)');
    }

    return aiInsertId($pdo, 'INSERT INTO ai_source (title, content) VALUES (:t, :c)', [
        ':t' => mb_substr(trim($title) ?: 'Методичка', 0, 200),
        ':c' => $content,
    ]);
}

function aiListSources(PDO $pdo): array
{
    ensureAiSchema($pdo);
    $rows = $pdo->query('SELECT id, title, LENGTH(content) AS size, created_at FROM ai_source ORDER BY id DESC')->fetchAll(PDO::FETCH_ASSOC);

    return array_map(static fn($r) => [
        'id' => (int)$r['id'], 'title' => $r['title'], 'size' => (int)$r['size'], 'createdAt' => $r['created_at'],
    ], $rows);
}

/** Случайный фрагмент методички, чтобы вопросы покрывали весь документ. */
function aiSourceChunk(PDO $pdo, int $sourceId): string
{
    $stmt = $pdo->prepare('SELECT content FROM ai_source WHERE id = :id');
    $stmt->execute([':id' => $sourceId]);
    $content = (string)$stmt->fetchColumn();
    if ($content === '') {
        throw new InvalidArgumentException('Методичка не найдена');
    }

    $length = mb_strlen($content);
    if ($length <= AI_SOURCE_CHUNK_CHARS) {
        return $content;
    }

    $start = random_int(0, $length - AI_SOURCE_CHUNK_CHARS);
    $paragraph = mb_strpos($content, "\n", $start);
    if ($paragraph !== false && $paragraph - $start < 1000) {
        $start = $paragraph + 1;
    }

    return mb_substr($content, $start, AI_SOURCE_CHUNK_CHARS);
}

