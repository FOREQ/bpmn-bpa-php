/**
 * Возвращает предложение ИИ по баллам за практику участника.
 * Ничего не записывает в Participant — только в ai_practical_review.
 */
function aiReviewPractical(PDO $pdo, array $participant): array
{
    ensureAiSchema($pdo);

    $taskIds = json_decode($participant['practicalTaskIds'] ?? '[]', true) ?: [];
    $answers = json_decode($participant['practicalAnswers'] ?? 'null', true) ?: [];
    $maxScores = [10, 15];
    $results = [];

    foreach (array_values($taskIds) as $index => $taskId) {
        if ($index > 1) {
            break;
        }
        $task = getPracticalTask((string)$taskId, $pdo);
        if (!$task) {
            continue;
        }
        $max = $maxScores[$index];
        $studentXml = (string)($answers['diagrams'][$task['id']]['xml'] ?? '');
        $student = bpmnSummarize($studentXml);

        if (!$student['valid'] || empty($student['stats']['sequenceFlow'])) {
            $results[] = [
                'taskId' => $task['id'], 'max' => $max, 'score' => 0,
                'summary' => 'Схема не сдана или пустая.', 'errors' => [], 'strengths' => [],
            ];
            continue;
        }

        $reference = aiTaskReference($pdo, $task);
        $structure = aiStructureCheck($pdo, $task, $studentXml, $student['stats']);
        $graded = aiGradeDiagram($task, $max, $student['text'], $reference, $structure);
        $graded['structure'] = $structure;
        $results[] = $graded;
    }

    $metrics = aiCheckComplexityAnswers($pdo, $participant, $answers);

    $suggestion = [
        'previousTaskScore' => (int)($results[0]['score'] ?? 0),
        'newTaskScore' => (int)($results[1]['score'] ?? 0),
        // Расчёт сложности проверяется автоматически только для заданий с эталонными ответами калькулятора.
        'metricsScore' => $metrics['score'] ?? null,
        'metrics' => $metrics,
        'tasks' => $results,
        'model' => aiConfig('grader')['model'],
        'createdAt' => date('Y-m-d H:i:s'),
    ];

    $pdo->prepare('INSERT INTO ai_practical_review (session_id, result_json, model) VALUES (:s, :r, :m)')
        ->execute([
            ':s' => $participant['sessionId'],
            ':r' => json_encode($suggestion, JSON_UNESCAPED_UNICODE),
            ':m' => $suggestion['model'],
        ]);

    return $suggestion;
}

