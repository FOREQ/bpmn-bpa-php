            ':p' => json_encode($payload, JSON_UNESCAPED_UNICODE), ':s' => $sourceId,
        ]);
    }

    return $created;
}

function aiNormalizeQuestion(array $q): ?array
{
    $ru = trim((string)($q['question_ru'] ?? ''));
    $kk = trim((string)($q['question_kk'] ?? ''));
    $optionsRu = array_values(array_map(static fn($o) => trim((string)$o), (array)($q['options_ru'] ?? [])));
    $optionsKk = array_values(array_map(static fn($o) => trim((string)$o), (array)($q['options_kk'] ?? [])));
    $correct = filter_var($q['correct_index'] ?? null, FILTER_VALIDATE_INT);

    if ($ru === '' || count($optionsRu) !== 4 || in_array('', $optionsRu, true)
        || $correct === false || $correct < 0 || $correct > 3) {
        return null;
    }
    if ($kk === '' || count($optionsKk) !== 4 || in_array('', $optionsKk, true)) {
        $kk = '';
        $optionsKk = [];
    }

    return [
        'question_ru' => mb_substr($ru, 0, 4000),
        'options_ru' => array_map(static fn($o) => mb_substr($o, 0, 1200), $optionsRu),
        'question_kk' => mb_substr($kk, 0, 4000),
        'options_kk' => array_map(static fn($o) => mb_substr($o, 0, 1200), $optionsKk),
        'correct_index' => $correct,
        'explanation' => mb_substr(trim((string)($q['explanation'] ?? '')), 0, 2000),
    ];
}

function aiGeneratePracticalTasks(PDO $pdo, string $pool, int $count, string $topic = '', ?int $sourceId = null): array
{
    ensureAiSchema($pdo);
    $count = max(1, min(5, $count));
    $examples = $pool === 'first' ? getFirstPracticalTasks() : getPracticalTasks();
    shuffle($examples);
    $examples = array_slice($examples, 0, 3);

    $level = $pool === 'first'
        ? 'Первое задание — простая бытовая история (семья, дом, хобби) на 3-5 предложений, 2-3 участника, '
          . 'можно параллельные действия или выбор. Цель — проверить базовое понимание дорожек, задач и потоков.'
        : 'Второе задание — процесс госоргана или организации (документооборот, обращения граждан, кадры, ИТ) на '
          . '4-7 предложений: 2-4 участника (дорожки), 5-10 задач, минимум одно ветвление (исключающее «или» или '
          . 'параллельное «и»), промежуточные/конечные события сообщений, где уместно.';

    $system = "Ты составляешь практические задания для экзамена по моделированию в BPMN 2.0. Участник читает "
        . "текстовое описание процесса и рисует схему. Текст должен однозначно задавать участников, порядок "
        . "действий и условия ветвлений, без лишних деталей, которые нельзя изобразить. {$level}\n"
        . "Для каждого задания дай описание на русском и казахском и эталонное решение словами: дорожки, "
        . "последовательность элементов (события, задачи, шлюзы с условиями), конечные события — так, чтобы "
        . "по нему другой экзаменатор мог проверить схему.\n\n"
        . "Ответ — строго JSON:\n"
        . '{"tasks":[{"title_ru":"","title_kk":"","description_ru":"","description_kk":"","solution_notes":""}]}';

    $user = "Сгенерируй {$count} новых заданий." . ($topic !== '' ? " Тематика: {$topic}." : '')
        . "\n\nПримеры существующих заданий (стиль и сложность, не повторять):\n";
    foreach ($examples as $example) {
        $user .= "- " . $example['description'] . "\n";
    }
    if ($sourceId) {
        $user .= "\nПри необходимости опирайся на фрагмент методички:\n<<<\n" . aiSourceChunk($pdo, $sourceId) . "\n>>>";
    }

    $json = aiChatJson([
        ['role' => 'system', 'content' => $system],
        ['role' => 'user', 'content' => $user],
    ], 'generator');

    $created = [];
    foreach ((array)($json['tasks'] ?? []) as $t) {
        $t = (array)$t;
        $description = trim((string)($t['description_ru'] ?? ''));
        if (mb_strlen($description) < 40) {
            continue;
        }
        $payload = [
            'title_ru' => mb_substr(trim((string)($t['title_ru'] ?? '')), 0, 300),
            'title_kk' => mb_substr(trim((string)($t['title_kk'] ?? '')), 0, 300),
            'description_ru' => mb_substr($description, 0, 6000),
            'description_kk' => mb_substr(trim((string)($t['description_kk'] ?? '')), 0, 6000),
            'solution_notes' => mb_substr(trim((string)($t['solution_notes'] ?? '')), 0, 6000),
        ];
        $payload = aiAttachReference($payload);
        $created[] = aiInsertId($pdo, 'INSERT INTO ai_draft (kind, target, payload_json, source_id) VALUES (:k, :t, :p, :s)', [
            ':k' => 'practical', ':t' => $pool,
            ':p' => json_encode($payload, JSON_UNESCAPED_UNICODE), ':s' => $sourceId,
        ]);
    }

    return $created;
}

/**
 * Текст процесса → BPMN: модель пишет IR, cct-mcp проверяет и раскладывает схему.
 * @return array{xml: string, ir: array}
 */
function aiTextToBpmn(string $text, string $name): array
{
    $guide = (string)file_get_contents(__DIR__ . '/../config/ai_ir_guide.md');
    $messages = [
        ['role' => 'system', 'content' => "Ты строишь модели бизнес-процессов в нотации BPMN 2.0 для учебных заданий. "
            . "По тексту процесса составь IR — JSON строго по формату ниже. Отвечай только JSON.\n\n" . $guide],
        ['role' => 'user', 'content' => "Название процесса: {$name}\n\nТекст процесса:\n{$text}"],
    ];

    $ir = aiChatJson($messages, 'generator');
    $ir = $ir['ir'] ?? $ir;
    for ($attempt = 0; $attempt < 2; $attempt++) {
        $check = cctValidateIr($ir);
        if ($check['ok']) {
            break;
        }
        if ($attempt === 1) {
            throw new BpmnServiceException("Модель не смогла построить корректную схему:\n" . mb_substr($check['errors'], 0, 800));
        }
        $messages[] = ['role' => 'assistant', 'content' => json_encode($ir, JSON_UNESCAPED_UNICODE)];
        $messages[] = ['role' => 'user', 'content' => "Проверка нашла ошибки, исправь IR и верни его целиком:\n" . $check['errors']];
        $ir = aiChatJson($messages, 'generator');
        $ir = $ir['ir'] ?? $ir;
    }

    return ['xml' => cctLayout($ir), 'ir' => $ir];
}

/** Задание 3: короткий текст процесса → схема → правильные ответы калькулятора. */
function aiGenerateComplexityTasks(PDO $pdo, int $count, string $topic = ''): array
{
    ensureAiSchema($pdo);
    $count = max(1, min(3, $count));

    $system = "Ты составляешь короткие описания бизнес-процессов госоргана или организации для задания «рассчитать "
        . "сложность процесса по схеме». В каждом: 2–4 участника (должности), 6–12 действий, хотя бы одно ветвление, "
        . "явно названные входящие документы (что поступает) и порождаемые документы (что создаётся), передачи "
        . "между участниками. 4–8 предложений, без лишних деталей.\n"
        . 'Ответ — строго JSON: {"tasks":[{"title":"...","description":"..."}]}';
    $json = aiChatJson([
        ['role' => 'system', 'content' => $system],
        ['role' => 'user', 'content' => "Составь {$count} описаний." . ($topic !== '' ? " Тематика: {$topic}." : '')],
    ], 'generator');

    $fields = getComplexityFieldsForCustom();
    $created = [];
    foreach (array_slice((array)($json['tasks'] ?? []), 0, $count) as $t) {
        $t = (array)$t;
        $description = trim((string)($t['description'] ?? ''));
        if (mb_strlen($description) < 40) {
            continue;
        }
        $title = mb_substr(trim((string)($t['title'] ?? '')) ?: 'Процесс', 0, 200);
        $built = aiTextToBpmn($description, $title);
        $calc = calculatorAnalyze($built['xml']);
        $payload = [
            'title' => $title,
            'description' => mb_substr($description, 0, 4000),
            'xml' => $built['xml'],
            'analyze' => $calc['analyze'],
            'issues' => calculatorIssueList($calc['issues']),
            'answers' => complexityAnswers($calc['analyze'], $fields),
        ];
        $created[] = aiInsertId($pdo, 'INSERT INTO ai_draft (kind, target, payload_json, source_id) VALUES (:k, :t, :p, NULL)', [
            ':k' => 'complexity', ':t' => 'complexity', ':p' => json_encode($payload, JSON_UNESCAPED_UNICODE),
        ]);
    }

    return $created;
}

/** Эталон .bpmn к сгенерированному практическому заданию (если сервисы настроены). */
function aiAttachReference(array $payload): array
{
    if (!cctMcpEnabled() || !aiEnabled('generator')) {
        return $payload;
    }
    try {
        $built = aiTextToBpmn($payload['description_ru'], $payload['title_ru'] ?: 'Процесс');
        $payload['reference_xml'] = $built['xml'];
        if (calculatorEnabled()) {
            $payload['reference_issues'] = calculatorIssueList(calculatorAnalyze($built['xml'])['issues']);
        }
    } catch (Throwable $e) {
        $payload['reference_error'] = mb_substr($e->getMessage(), 0, 500);
    }

    return $payload;
}

function aiStoreBpmnFile(string $directory, string $xml): string
{
    $dir = __DIR__ . '/../assets/' . $directory;
    if (!is_dir($dir) && !mkdir($dir, 0755, true)) {
        throw new RuntimeException('Не удалось создать папку ' . $directory);
    }
    $name = 'ai_' . bin2hex(random_bytes(8)) . '.bpmn';
    if (file_put_contents($dir . '/' . $name, $xml) === false) {
        throw new RuntimeException('Не удалось сохранить схему');
    }

    return $name;
}

function aiListDrafts(PDO $pdo, string $status = 'pending'): array
{
    ensureAiSchema($pdo);
    $stmt = $pdo->prepare('SELECT id, kind, target, payload_json, status, published_id, created_at FROM ai_draft WHERE status = :s ORDER BY id DESC LIMIT 200');
    $stmt->execute([':s' => $status]);

    return array_map(static fn($r) => [
        'id' => (int)$r['id'],
        'kind' => $r['kind'],
        'target' => $r['target'],
        'payload' => json_decode($r['payload_json'], true),
        'status' => $r['status'],
        'publishedId' => $r['published_id'] !== null ? (int)$r['published_id'] : null,
        'createdAt' => $r['created_at'],
    ], $stmt->fetchAll(PDO::FETCH_ASSOC));
}

/**
 * Одобрение черновика: переносит его в custom_question / custom_practical_task.
 * $edited — правки администратора (те же поля, что в payload).
 */
function aiApproveDraft(PDO $pdo, int $draftId, array $edited = []): int
{
    ensureAiSchema($pdo);
    $stmt = $pdo->prepare("SELECT * FROM ai_draft WHERE id = :id AND status = 'pending'");
    $stmt->execute([':id' => $draftId]);
    $draft = $stmt->fetch(PDO::FETCH_ASSOC);
    if (!$draft) {
        throw new InvalidArgumentException('Черновик не найден или уже обработан');
    }

    $payload = array_merge(json_decode($draft['payload_json'], true) ?: [], $edited);
    $target = (string)($edited['target'] ?? $draft['target']);

    if ($draft['kind'] === 'question') {
        $payload = aiNormalizeQuestion($payload);
        if ($payload === null || !in_array($target, ['A', 'B', 'C', 'all'], true)) {
            throw new InvalidArgumentException('Вопрос заполнен не полностью: нужен текст, 4 ответа и правильный ответ');
        }
        $publishedId = aiInsertId($pdo, 'INSERT INTO custom_question (variant, question_text, question_text_kk, options_json, options_json_kk, correct_index, image_path)
            VALUES (:v, :q, :qk, :o, :ok, :c, NULL)', [
            ':v' => $target,
            ':q' => $payload['question_ru'],
            ':qk' => $payload['question_kk'] !== '' ? $payload['question_kk'] : null,
            ':o' => json_encode($payload['options_ru'], JSON_UNESCAPED_UNICODE),
            ':ok' => $payload['options_kk'] ? json_encode($payload['options_kk'], JSON_UNESCAPED_UNICODE) : null,
            ':c' => $payload['correct_index'],
        ]);
    } elseif ($draft['kind'] === 'complexity') {
        if (empty($payload['xml']) || empty($payload['answers'])) {
            throw new InvalidArgumentException('В черновике нет схемы или ответов калькулятора');
        }
        $file = aiStoreBpmnFile('complexity', (string)$payload['xml']);
        $publishedId = aiInsertId($pdo, 'INSERT INTO custom_complexity_task (title, description, bpmn_file, answers_json, analyze_json)
            VALUES (:t, :d, :f, :a, :z)', [
            ':t' => (string)($payload['title'] ?? ''),
            ':d' => (string)($payload['description'] ?? ''),
            ':f' => $file,
            ':a' => json_encode($payload['answers'], JSON_UNESCAPED_UNICODE),
            ':z' => json_encode($payload['analyze'] ?? [], JSON_UNESCAPED_UNICODE),
        ]);
        $target = 'complexity';
    } else {
        $description = trim((string)($payload['description_ru'] ?? ''));
        if ($description === '' || !in_array($target, ['first', 'second'], true)) {
            throw new InvalidArgumentException('Нужно описание задания и пул (first/second)');
        }
        $publishedId = aiInsertId($pdo, 'INSERT INTO custom_practical_task (pool, title, title_kk, description, description_kk, reference_file, solution_notes)
            VALUES (:p, :t, :tk, :d, :dk, :r, :n)', [
            ':r' => !empty($payload['reference_xml']) ? aiStoreBpmnFile('reference_bpmn', (string)$payload['reference_xml']) : null,
            ':p' => $target,
            ':t' => trim((string)($payload['title_ru'] ?? '')) ?: null,
            ':tk' => trim((string)($payload['title_kk'] ?? '')) ?: null,
            ':d' => $description,
            ':dk' => trim((string)($payload['description_kk'] ?? '')) ?: null,
            ':n' => trim((string)($payload['solution_notes'] ?? '')) ?: null,
        ]);
    }

    $pdo->prepare("UPDATE ai_draft SET status = 'approved', published_id = :pid, target = :t, payload_json = :p, reviewed_at = CURRENT_TIMESTAMP WHERE id = :id")
        ->execute([':pid' => $publishedId, ':t' => $target, ':p' => json_encode($payload, JSON_UNESCAPED_UNICODE), ':id' => $draftId]);

    return $publishedId;
}

function aiRejectDraft(PDO $pdo, int $draftId): void
{
    ensureAiSchema($pdo);
    $pdo->prepare("UPDATE ai_draft SET status = 'rejected', reviewed_at = CURRENT_TIMESTAMP WHERE id = :id AND status = 'pending'")
        ->execute([':id' => $draftId]);
}
