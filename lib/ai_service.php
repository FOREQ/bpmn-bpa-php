/**
 * Одобрение черновика: переносит его в custom_question / custom_practical_task.
 * $edited — правки администратора (те же поля, что в payload).
 */
function aiApproveDraft(PDO $pdo, int $draftId, array $edited = []): int
{
    ensureAiSchema($pdo);
    $stmt = $pdo->prepare("SELECT * FROM ai_draft WHERE id = :id AND status = 'pending'");
    $stmt->execute([':id' => $draftId]);
    $draft = $stmt->fetch(PDO::FETCH_ASSOC);
    if (!$draft) {
        throw new InvalidArgumentException('Черновик не найден или уже обработан');
    }

    $payload = array_merge(json_decode($draft['payload_json'], true) ?: [], $edited);
    $target = (string)($edited['target'] ?? $draft['target']);

    if ($draft['kind'] === 'question') {
        $payload = aiNormalizeQuestion($payload);
        if ($payload === null || !in_array($target, ['A', 'B', 'C', 'all'], true)) {
            throw new InvalidArgumentException('Вопрос заполнен не полностью: нужен текст, 4 ответа и правильный ответ');
        }
        $publishedId = aiInsertId($pdo, 'INSERT INTO custom_question (variant, question_text, question_text_kk, options_json, options_json_kk, correct_index, image_path)
            VALUES (:v, :q, :qk, :o, :ok, :c, NULL)', [
            ':v' => $target,
            ':q' => $payload['question_ru'],
            ':qk' => $payload['question_kk'] !== '' ? $payload['question_kk'] : null,
            ':o' => json_encode($payload['options_ru'], JSON_UNESCAPED_UNICODE),
            ':ok' => $payload['options_kk'] ? json_encode($payload['options_kk'], JSON_UNESCAPED_UNICODE) : null,
            ':c' => $payload['correct_index'],
        ]);
    } else {
        $description = trim((string)($payload['description_ru'] ?? ''));
        if ($description === '' || !in_array($target, ['first', 'second'], true)) {
            throw new InvalidArgumentException('Нужно описание задания и пул (first/second)');
        }
        $publishedId = aiInsertId($pdo, 'INSERT INTO custom_practical_task (pool, title, title_kk, description, description_kk, reference_file, solution_notes)
            VALUES (:p, :t, :tk, :d, :dk, NULL, :n)', [
            ':p' => $target,
            ':t' => trim((string)($payload['title_ru'] ?? '')) ?: null,
            ':tk' => trim((string)($payload['title_kk'] ?? '')) ?: null,
            ':d' => $description,
            ':dk' => trim((string)($payload['description_kk'] ?? '')) ?: null,
            ':n' => trim((string)($payload['solution_notes'] ?? '')) ?: null,
        ]);
    }

    $pdo->prepare("UPDATE ai_draft SET status = 'approved', published_id = :pid, target = :t, payload_json = :p, reviewed_at = CURRENT_TIMESTAMP WHERE id = :id")
        ->execute([':pid' => $publishedId, ':t' => $target, ':p' => json_encode($payload, JSON_UNESCAPED_UNICODE), ':id' => $draftId]);

    return $publishedId;
}

function aiRejectDraft(PDO $pdo, int $draftId): void
{
    ensureAiSchema($pdo);
    $pdo->prepare("UPDATE ai_draft SET status = 'rejected', reviewed_at = CURRENT_TIMESTAMP WHERE id = :id AND status = 'pending'")
        ->execute([':id' => $draftId]);
}
