<?php

/**
 * Фоновые задачи ИИ: генерация и проверка идут в отдельном процессе PHP (scripts/ai_worker.php),
 * а страница опрашивает статус. Так долгий запрос к модели не держит воркер веб-сервера
 * и не упирается в таймауты прокси.
 */

require_once __DIR__ . '/ai_service.php';

/** Задача, которая «работает» дольше этого, считается упавшей (процесс убит, контейнер перезапущен). */
const AI_JOB_STALE_SECONDS = 1800;

const AI_JOB_ACTIONS = ['generate_questions', 'generate_practical', 'generate_complexity', 'review'];

function ensureAiJobSchema(PDO $pdo): void
{
    static $checked = false;
    if ($checked) {
        return;
    }
    $pg = $pdo->getAttribute(PDO::ATTR_DRIVER_NAME) === 'pgsql';
    $id = $pg ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT';
    $ts = $pg ? 'TIMESTAMP' : 'DATETIME';
    $pdo->exec("CREATE TABLE IF NOT EXISTS ai_job (
        id $id,
        action TEXT NOT NULL,
        params_json TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'queued',
        result_json TEXT,
        error TEXT,
        created_at $ts NOT NULL DEFAULT CURRENT_TIMESTAMP,
        started_at $ts,
        finished_at $ts)");
    $checked = true;
}

function aiJobCreate(PDO $pdo, string $action, array $params): int
{
    if (!in_array($action, AI_JOB_ACTIONS, true)) {
        throw new InvalidArgumentException('Неизвестное действие');
    }
    ensureAiJobSchema($pdo);

    return aiInsertId($pdo, 'INSERT INTO ai_job (action, params_json, status) VALUES (:a, :p, \'queued\')', [
        ':a' => $action,
        ':p' => json_encode($params, JSON_UNESCAPED_UNICODE),
    ]);
}

/** @return array{id:int,action:string,status:string,result:mixed,error:?string}|null */
function aiJobGet(PDO $pdo, int $id): ?array
{
    ensureAiJobSchema($pdo);
    $stmt = $pdo->prepare('SELECT * FROM ai_job WHERE id = :id');
    $stmt->execute([':id' => $id]);
    $row = $stmt->fetch(PDO::FETCH_ASSOC);
    if (!$row) {
        return null;
    }

    if (in_array($row['status'], ['queued', 'running'], true) && aiJobIsStale($pdo, $id)) {
        $row['status'] = 'failed';
        $row['error'] = 'Задача прервалась (сервер перезапускался?). Запустите заново.';
        aiJobFinish($pdo, $id, 'failed', null, $row['error']);
    }

    return [
        'id' => (int)$row['id'],
        'action' => (string)$row['action'],
        'status' => (string)$row['status'],
        'result' => $row['result_json'] !== null ? json_decode((string)$row['result_json'], true) : null,
        'error' => $row['error'],
    ];
}

/** Время сравнивается в самой БД: CURRENT_TIMESTAMP в SQLite — UTC, а PHP работает в часовом поясе портала. */
function aiJobIsStale(PDO $pdo, int $id): bool
{
    $pg = $pdo->getAttribute(PDO::ATTR_DRIVER_NAME) === 'pgsql';
    $limit = $pg
        ? "CURRENT_TIMESTAMP - INTERVAL '" . AI_JOB_STALE_SECONDS . " seconds'"
        : "datetime('now', '-" . AI_JOB_STALE_SECONDS . " seconds')";
    $stmt = $pdo->prepare("SELECT 1 FROM ai_job WHERE id = :id AND COALESCE(started_at, created_at) < $limit");
    $stmt->execute([':id' => $id]);

    return (bool)$stmt->fetchColumn();
}

function aiJobFinish(PDO $pdo, int $id, string $status, ?array $result, ?string $error): void
{
    $stmt = $pdo->prepare('UPDATE ai_job SET status = :s, result_json = :r, error = :e, finished_at = CURRENT_TIMESTAMP WHERE id = :id');
    $stmt->execute([
        ':s' => $status,
        ':r' => $result !== null ? json_encode($result, JSON_UNESCAPED_UNICODE | JSON_INVALID_UTF8_SUBSTITUTE) : null,
        ':e' => $error !== null ? mb_substr($error, 0, 2000) : null,
        ':id' => $id,
    ]);
}

/**
 * Запускает scripts/ai_worker.php отдельным процессом. Если запуск процессов запрещён,
 * возвращает false — тогда задачу надо выполнить прямо в запросе (как раньше).
 */
function aiJobSpawn(int $id): bool
{
    if (aiFlag(aiEnv('AI_JOBS_INLINE', '0')) || !function_exists('exec')
        || in_array('exec', array_map('trim', explode(',', (string)ini_get('disable_functions'))), true)) {
        return false;
    }
    $php = PHP_BINARY !== '' ? PHP_BINARY : 'php';
    $script = realpath(__DIR__ . '/../scripts/ai_worker.php');
    $log = __DIR__ . '/../logs/ai_worker.log';
    $cmd = 'nohup ' . escapeshellarg($php) . ' ' . escapeshellarg((string)$script) . ' ' . (int)$id
        . ' >> ' . escapeshellarg($log) . ' 2>&1 &';
    exec($cmd, $output, $code);

    return $code === 0;
}

/** Выполняет задачу в текущем процессе и записывает результат. */
function aiJobRun(PDO $pdo, int $id): void
{
    ensureAiJobSchema($pdo);
    // Забираем задачу атомарно: второй воркер с тем же id ничего не сделает.
    $claim = $pdo->prepare("UPDATE ai_job SET status = 'running', started_at = CURRENT_TIMESTAMP WHERE id = :id AND status = 'queued'");
    $claim->execute([':id' => $id]);
    if ($claim->rowCount() !== 1) {
        return;
    }
    $stmt = $pdo->prepare('SELECT action, params_json FROM ai_job WHERE id = :id');
    $stmt->execute([':id' => $id]);
    $row = $stmt->fetch(PDO::FETCH_ASSOC);

    try {
        $result = aiJobExecute($pdo, (string)$row['action'], (array)json_decode((string)$row['params_json'], true));
        aiJobFinish($pdo, $id, 'done', $result, null);
    } catch (AiNotConfiguredException | AiRequestException | BpmnServiceException | InvalidArgumentException $e) {
        aiJobFinish($pdo, $id, 'failed', null, $e->getMessage());
    } catch (Throwable $e) {
        if (function_exists('logError')) {
            logError($e, 'ai_job ' . $id);
        }
        aiJobFinish($pdo, $id, 'failed', null, 'Произошла ошибка сервера');
    }
}

function aiJobExecute(PDO $pdo, string $action, array $p): array
{
    ensureAiSchema($pdo);
    switch ($action) {
        case 'generate_questions':
            $ids = aiGenerateQuestions($pdo, (int)($p['sourceId'] ?? 0), (string)($p['variant'] ?? 'all'),
                (int)($p['count'] ?? 5), (string)($p['topic'] ?? ''));

            return ['created' => count($ids)];
        case 'generate_practical':
            $sourceId = (int)($p['sourceId'] ?? 0);
            $ids = aiGeneratePracticalTasks($pdo, (string)($p['pool'] ?? 'second'), (int)($p['count'] ?? 2),
                (string)($p['topic'] ?? ''), $sourceId > 0 ? $sourceId : null);

            return ['created' => count($ids)];
        case 'generate_complexity':
            $ids = aiGenerateComplexityTasks($pdo, (int)($p['count'] ?? 1), (string)($p['topic'] ?? ''));

            return ['created' => count($ids)];
        case 'review':
            $stmt = $pdo->prepare('SELECT * FROM Participant WHERE sessionId = :s LIMIT 1');
            $stmt->execute([':s' => (string)($p['sessionId'] ?? '')]);
            $participant = $stmt->fetch(PDO::FETCH_ASSOC);
            if (!$participant || empty($participant['practicalSubmittedAt'])) {
                throw new InvalidArgumentException('Практика участника не найдена или не сдана');
            }

            return ['review' => aiReviewPractical($pdo, $participant)];
    }
    throw new InvalidArgumentException('Неизвестное действие');
}
