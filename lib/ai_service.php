const AI_SOURCE_MAX_CHARS = 2_000_000;
const AI_SOURCE_CHUNK_CHARS = 14_000;

function ensureAiSchema(PDO $pdo): void
{
    static $checked = false;
    if ($checked) {
        return;
    }
    ensureCustomContentSchema($pdo);

    $pg = $pdo->getAttribute(PDO::ATTR_DRIVER_NAME) === 'pgsql';
    $id = $pg ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT';
    $ts = $pg ? 'TIMESTAMP' : 'DATETIME';

    $pdo->exec("CREATE TABLE IF NOT EXISTS ai_source (
        id $id,
        title TEXT NOT NULL,
        content TEXT NOT NULL,
        created_at $ts NOT NULL DEFAULT CURRENT_TIMESTAMP)");
    $pdo->exec("CREATE TABLE IF NOT EXISTS ai_draft (
        id $id,
        kind TEXT NOT NULL,
        target TEXT NOT NULL,
        payload_json TEXT NOT NULL,
        source_id BIGINT,
        status TEXT NOT NULL DEFAULT 'pending',
        published_id BIGINT,
        created_at $ts NOT NULL DEFAULT CURRENT_TIMESTAMP,
        reviewed_at $ts)");
    $pdo->exec("CREATE TABLE IF NOT EXISTS ai_practical_review (
        id $id,
        session_id TEXT NOT NULL,
        result_json TEXT NOT NULL,
        model TEXT,
        created_at $ts NOT NULL DEFAULT CURRENT_TIMESTAMP)");
    $pdo->exec('CREATE INDEX IF NOT EXISTS idx_ai_review_session ON ai_practical_review(session_id)');
    $pdo->exec('CREATE INDEX IF NOT EXISTS idx_ai_draft_status ON ai_draft(status)');

    // Эталонное решение «словами» для заданий, созданных ИИ (если нет .bpmn-эталона).
    if ($pg) {
        $pdo->exec('ALTER TABLE custom_practical_task ADD COLUMN IF NOT EXISTS solution_notes TEXT');
    } else {
        $columns = array_column($pdo->query('PRAGMA table_info(custom_practical_task)')->fetchAll(PDO::FETCH_ASSOC), 'name');
        if (!in_array('solution_notes', $columns, true)) {
            $pdo->exec('ALTER TABLE custom_practical_task ADD COLUMN solution_notes TEXT');
        }
    }

    $checked = true;
}

function aiInsertId(PDO $pdo, string $sql, array $params): int
{
    if ($pdo->getAttribute(PDO::ATTR_DRIVER_NAME) === 'pgsql') {
        $stmt = $pdo->prepare($sql . ' RETURNING id');
        $stmt->execute($params);

        return (int)$stmt->fetchColumn();
    }
    $pdo->prepare($sql)->execute($params);

    return (int)$pdo->lastInsertId();
}

