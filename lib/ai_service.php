/**
 * Возвращает предложение ИИ по баллам за практику участника.
 * Ничего не записывает в Participant — только в ai_practical_review.
 */
function aiReviewPractical(PDO $pdo, array $participant): array
{
    ensureAiSchema($pdo);

    $taskIds = json_decode($participant['practicalTaskIds'] ?? '[]', true) ?: [];
    $answers = json_decode($participant['practicalAnswers'] ?? 'null', true) ?: [];
    $maxScores = [10, 15];
    $results = [];

    foreach (array_values($taskIds) as $index => $taskId) {
        if ($index > 1) {
            break;
        }
        $task = getPracticalTask((string)$taskId, $pdo);
        if (!$task) {
            continue;
        }
        $max = $maxScores[$index];
        $studentXml = (string)($answers['diagrams'][$task['id']]['xml'] ?? '');
        $student = bpmnSummarize($studentXml);

        if (!$student['valid'] || empty($student['stats']['sequenceFlow'])) {
            $results[] = [
                'taskId' => $task['id'], 'max' => $max, 'score' => 0,
                'summary' => 'Схема не сдана или пустая.', 'errors' => [], 'strengths' => [],
            ];
            continue;
        }

        $reference = aiTaskReference($pdo, $task);
        $results[] = aiGradeDiagram($task, $max, $student['text'], $reference);
    }

    $suggestion = [
        'previousTaskScore' => (int)($results[0]['score'] ?? 0),
        'newTaskScore' => (int)($results[1]['score'] ?? 0),
        // Расчёт сложности сверяется с картинкой варианта — оставляем админу.
        'metricsScore' => null,
        'tasks' => $results,
        'model' => aiConfig('grader')['model'],
        'createdAt' => date('Y-m-d H:i:s'),
    ];

    $pdo->prepare('INSERT INTO ai_practical_review (session_id, result_json, model) VALUES (:s, :r, :m)')
        ->execute([
            ':s' => $participant['sessionId'],
            ':r' => json_encode($suggestion, JSON_UNESCAPED_UNICODE),
            ':m' => $suggestion['model'],
        ]);

    return $suggestion;
}

function aiLatestReview(PDO $pdo, string $sessionId): ?array
{
    ensureAiSchema($pdo);
    $stmt = $pdo->prepare('SELECT result_json FROM ai_practical_review WHERE session_id = :s ORDER BY id DESC LIMIT 1');
    $stmt->execute([':s' => $sessionId]);
    $json = $stmt->fetchColumn();

    return $json ? json_decode((string)$json, true) : null;
}

/** Описание эталона: .bpmn-файл → краткая схема; иначе — заметки к решению. */
function aiTaskReference(PDO $pdo, array $task): string
{
    $file = $task['referenceBpmn'] ?? null;
    if ($file && preg_match('/^[A-Za-z0-9._-]+\.bpmn$/', $file)) {
        $path = __DIR__ . '/../assets/reference_bpmn/' . $file;
        if (is_file($path)) {
            return "Эталонная схема (одно из допустимых решений):\n" . bpmnSummarize((string)file_get_contents($path))['text'];
        }
    }

    if (preg_match('/^custom-([1-9][0-9]*)$/', (string)$task['id'], $m)) {
        $stmt = $pdo->prepare('SELECT solution_notes FROM custom_practical_task WHERE id = :id');
        $stmt->execute([':id' => $m[1]]);
        $notes = trim((string)$stmt->fetchColumn());
        if ($notes !== '') {
            return "Ожидаемое решение (описание):\n" . $notes;
        }
    }

    return 'Эталона нет — оценивай по тексту задания и правилам BPMN.';
}

