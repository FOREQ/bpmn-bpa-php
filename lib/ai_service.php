function aiExistingQuestionTexts(PDO $pdo, int $limit = 80): array
{
    global $TEST_DATA;
    require_once __DIR__ . '/test_data.php';

    $texts = [];
    foreach ($TEST_DATA ?? [] as $questions) {
        foreach ($questions as $q) {
            $texts[] = $q['question'];
        }
    }
    foreach ($pdo->query('SELECT question_text FROM custom_question')->fetchAll(PDO::FETCH_COLUMN) as $t) {
        $texts[] = $t;
    }
    $texts = array_values(array_unique($texts));
    shuffle($texts);

    return array_slice($texts, 0, $limit);
}

